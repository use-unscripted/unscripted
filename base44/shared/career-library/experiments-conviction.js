/**
 * Conviction Test Library: the tests that complete a career's balance.
 *
 * The original library covered representative core work and the difficult
 * realities well, and left three purposes thin across most careers: the work
 * ENVIRONMENT (the conditions rather than the task), the TRADEOFFS (what the work
 * would cost), and CONTRADICTION and COMPARISON tests (whether a reading holds
 * up, and how this work differs from the neighbouring path a student is weighing
 * it against).
 *
 * Each entry below is written against that career's role blueprint — its own
 * pace, interruption pattern, hierarchy and deliverables — and each says what it
 * cannot simulate. Careers whose remaining purposes could only be filled with a
 * generic activity are deliberately left uncovered: the coverage report names
 * the gap so it can be authored properly, and an uncovered purpose is more
 * honest than a test that measures nothing in particular.
 *
 * Every entry carries `purpose`. Versioning, validation level, sources and
 * strength are unchanged: these are ordinary library templates, seeded through
 * the same path, landing at Source Grounded until a professional reviews them.
 */

